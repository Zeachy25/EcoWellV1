enum AiRole { user, assistant }

/// An exercise the assistant can offer to launch.
enum AiAction { breathing, grounding }

/// One message in the AI coach conversation.
class AiMessage {
  const AiMessage({
    required this.id,
    required this.role,
    required this.content,
    required this.createdAt,
    this.isLocal = false,
    this.isLocalFallback = false,
    this.action,
  });

  final String id;
  final AiRole role;
  final String content;
  final DateTime createdAt;

  /// True for messages that were created on this phone (for example an
  /// offline fallback suggestion) and have not been stored on the server.
  final bool isLocal;

  /// True only for replies generated by the offline fallback path.
  final bool isLocalFallback;

  /// Optional guided exercise the assistant is inviting the user to start.
  final AiAction? action;

  bool get isUser => role == AiRole.user;

  static AiAction? actionFromJson(Object? value) {
    switch (value) {
      case 'breathing':
        return AiAction.breathing;
      case 'grounding':
        return AiAction.grounding;
      default:
        return null;
    }
  }

  factory AiMessage.fromJson(Map<String, dynamic> json) {
    final role = json['role'] == 'assistant' ? AiRole.assistant : AiRole.user;
    final isLocal = json['is_local'] as bool? ?? false;
    final createdAt = DateTime.tryParse(
      json['created_at'] as String? ?? '',
    )?.toLocal();
    return AiMessage(
      id:
          json['id'] as String? ??
          'local:${createdAt?.microsecondsSinceEpoch ?? 0}',
      role: role,
      content: json['content'] as String? ?? '',
      createdAt: createdAt ?? DateTime.now(),
      isLocal: isLocal,
      isLocalFallback:
          json['is_local_fallback'] as bool? ??
          (isLocal && role == AiRole.assistant),
      action: actionFromJson(json['action']),
    );
  }

  factory AiMessage.local({
    required AiRole role,
    required String content,
    DateTime? createdAt,
    bool isLocalFallback = false,
    AiAction? action,
  }) {
    final stamp = createdAt ?? DateTime.now();
    return AiMessage(
      id: 'local:${stamp.microsecondsSinceEpoch}',
      role: role,
      content: content,
      createdAt: stamp,
      isLocal: true,
      isLocalFallback: isLocalFallback,
      action: action,
    );
  }

  Map<String, dynamic> toJson() => {
    'id': id,
    'role': role == AiRole.assistant ? 'assistant' : 'user',
    'content': content,
    'created_at': createdAt.toUtc().toIso8601String(),
    'is_local': isLocal,
    'is_local_fallback': isLocalFallback,
    'action': action?.name,
  };
}

/// The assistant's answer plus whether it came from the crisis safety path.
class AiReply {
  const AiReply({
    required this.reply,
    required this.crisis,
    this.action,
    this.messages = const [],
  });

  final String reply;
  final bool crisis;

  /// The exercise the assistant offered, if any.
  final AiAction? action;

  /// The server-saved rows, when the function returned them. The chat
  /// controller uses these instead of the optimistic local copies.
  final List<AiMessage> messages;
}

/// A typed failure from the AI repository.
class AiException implements Exception {
  const AiException(this.code, this.message);

  final String code;
  final String message;

  bool get canUseFallback =>
      code == 'offline' || code == 'timeout' || code == 'ai_unavailable';

  @override
  String toString() => 'AiException($code): $message';
}
